#!/usr/bin/env node
// Writes the question bank (questions/*.md) into index.html as the common questions that the forum and the degree, technician and occupation
// pages show, between the lines "QA:begin" and "QA:end". Nothing else in the file is touched, and its line endings are kept.
//
//   node tools/apply-qa.mjs            writes
//   node tools/apply-qa.mjs --check    changes nothing; exit code 1 when index.html is not what the markdown would write
//   node tools/apply-qa.mjs --partial  while the answers are being written: the questions that have no answer yet are left out
//
// The page reads two lists: QA_T (a track: id, title, category, kind, match, attach, occ) and QA_I (a question: track number, id, forum topic,
// question, answer). The page itself finds the degrees, technician programs and occupations that a track belongs to, with the same
// regular expressions that tools/question-bank.mjs checks (see qaTracks() in index.html).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { SITE, loadSite } from './lib/site-data.mjs';
import { readBank, validate, build, coverage } from './question-bank.mjs';

export const BEGIN = '/* QA:begin';
export const END = '/* QA:end */';
const HEAD = BEGIN + ' (generated by tools/apply-qa.mjs from questions/*.md: change the markdown, then run node tools/apply-qa.mjs) */';

/** The lines of the block, without line endings. */
export function qaBlock(bank) {
  const at = new Map(bank.tracks.map((t, i) => [t.id, i]));
  const rows = (list) => list.map((x, i) => JSON.stringify(x) + (i < list.length - 1 ? ',' : ''));
  const T = bank.tracks.map((t) => [t.id, t.title, t.category, t.kind, t.match || '', t.attach || '', t.occ || '']);
  const I = bank.questions.filter((q) => q.a).map((q) => [at.get(q.track), q.id, q.topic, q.q, q.a]);   // a question without an answer is not shown
  return [HEAD, 'const QA_T=[', ...rows(T), '];', 'const QA_I=[', ...rows(I), '];', END];
}

/** index.html with the block written in: it replaces the old one, or it goes before `let DEMO_C=null;` the first time. */
export function withBlock(text, block) {
  const eol = text.includes('\r\n') ? '\r\n' : '\n';
  const lines = text.split(eol);
  const a = lines.findIndex((l) => l.startsWith(BEGIN)), b = lines.findIndex((l) => l.startsWith(END));
  if (a >= 0 && b > a) lines.splice(a, b - a + 1, ...block);
  else {
    const at = lines.findIndex((l) => l.startsWith('let DEMO_C=null;'));
    if (at < 0) throw new Error('the place for the block (the line `let DEMO_C=null;`) was not found');
    lines.splice(at, 0, ...block);
  }
  return lines.join(eol);
}

/** The block as it stands in a text, or null. */
export function blockOf(text) {
  const lines = text.split(/\r?\n/);
  const a = lines.findIndex((l) => l.startsWith(BEGIN)), b = lines.findIndex((l) => l.startsWith(END));
  return a >= 0 && b > a ? lines.slice(a, b + 1) : null;
}

function main() {
  const check = process.argv.includes('--check'), partial = process.argv.includes('--partial');
  const files = readBank(), site = loadSite();
  const { errors } = validate(files, { site, requireAnswers: !partial });
  if (errors.length) { for (const e of errors.slice(0, 20)) console.error(`ERROR ${e.file}:${e.line} ${e.msg}`); console.error(`${errors.length} errors in the question bank: nothing was written`); process.exit(1); }
  const block = qaBlock(build(files, coverage(files, site.DATA)));
  const text = readFileSync(SITE, 'utf8');
  const now = blockOf(text);
  const same = now && now.length === block.length && now.every((l, i) => l === block[i]);
  if (check) { console.log(same ? 'index.html carries the question bank as it is now' : 'index.html is not up to date: run node tools/apply-qa.mjs'); process.exit(same ? 0 : 1); }
  if (same) { console.log('index.html is already up to date'); return; }
  writeFileSync(SITE, withBlock(text, block));
  const n = block.length - 6;
  console.log(`index.html: the question bank written (${n} lines)`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
